const axios = require('axios');

const processAIRequest = async ({ actionType, prompt, code = '', language = 'javascript', persona = 'Architect' }) => {
  const apiKey = process.env.AI_API_KEY;

  if (apiKey && apiKey !== 'your_gemini_api_key_here') {
    try {
      const response = await axios.post(
        `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`,
        {
          contents: [{
            parts: [{
              text: `System Persona: You are an expert AI Developer Assistant operating in "${persona}" mode for CodeSync AI.
Action Requested: ${actionType}
Programming Language: ${language}
Context Code:
\`\`\`${language}
${code}
\`\`\`

User Request/Prompt:
${prompt}
`
            }]
          }]
        },
        { headers: { 'Content-Type': 'application/json' }, timeout: 12000 }
      );

      const candidates = response.data.candidates;
      if (candidates && candidates[0] && candidates[0].content) {
        return candidates[0].content.parts[0].text;
      }
    } catch (err) {
      console.warn('[AI Service] Gemini API call deferred, switching to intelligent persona heuristic:', err.message);
    }
  }

  // Intelligent Fallback Persona Heuristic Engine
  return generateHeuristicAIResponse({ actionType, prompt, code, language, persona });
};

